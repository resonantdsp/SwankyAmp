//! Measures the shipping path's level compensation (the preamp and output
//! tables and the tone-stack scale) against the released 1.4.0 path and writes
//! it as source. `--check` fails unless the committed values match a fresh
//! measurement.

use std::env;
use std::fs;

use swanky_amp::dsp::amp::{LevelTables, TABLE_POINTS};
use swanky_amp::dsp::calibration::{self, Calibration, Point};

/// Platform libm differences move a table point by far less than this; a
/// change to the shipping sound moves it by more.
const TOLERANCE_DB: f64 = 0.05;

fn option(name: &str) -> Result<String, String> {
    let arguments: Vec<String> = env::args().collect();
    arguments
        .windows(2)
        .find(|pair| pair[0] == name)
        .map(|pair| pair[1].clone())
        .ok_or_else(|| format!("missing option: {name}"))
}

fn db(ratio: f64) -> f64 {
    20. * ratio.log10()
}

/// Seven significant digits in the released tables' literal style, which
/// keeps every entry long enough that rustfmt lays the array out one per line.
fn literal(value: f32) -> String {
    let text = format!("{value:.6e}");
    let (mantissa, exponent) = text.split_once('e').expect("exponent form");
    format!("{}_{}e{exponent}", &mantissa[..5], &mantissa[5..])
}

fn table(name: &str, values: &[f32; TABLE_POINTS]) -> String {
    let mut text = format!(
        "#[allow(clippy::excessive_precision)] // Written to seven significant digits.\n\
         pub(super) const {name}: [f32; {TABLE_POINTS}] = [\n"
    );
    for value in values {
        text.push_str(&format!("    {},\n", literal(*value)));
    }
    text.push_str("];\n");
    text
}

fn source(tables: LevelTables) -> String {
    format!(
        "//! Generated by `just calibrate`; `just calibrate-check` proves it is current.\n\
         //! See `calibration` for what these measure.\n\n{}\n\
         #[allow(clippy::excessive_precision)] // Written to seven significant digits.\n\
         pub(super) const TONE_STACK_SCALE: f32 = {};\n\n{}",
        table("PREAMP_SWEEP", &tables.preamp),
        literal(tables.tone_stack),
        table("POWER_SWEEP", &tables.power),
    )
}

fn sweep(title: &str, seam: &str, points: &[Point; TABLE_POINTS], released: &[f32], new: &[f32]) {
    println!(
        "{title}\n  point  released {seam} dB  shipping dB  released table  new table  change dB"
    );
    for (index, point) in points.iter().enumerate() {
        println!(
            "  {:+.1}   {:>16.2}  {:>11.2}  {:>14.6e}  {:>9.6e}  {:+9.2}",
            -1. + 0.2 * index as f64,
            point.released_db,
            point.shipping_db,
            released[index],
            new[index],
            db(f64::from(new[index]) / f64::from(released[index])),
        );
    }
}

fn report(calibration: &Calibration) {
    let released = LevelTables::RELEASED;
    sweep(
        "Drive, last active triode",
        "triode",
        &calibration.drive,
        &released.preamp,
        &calibration.tables.preamp,
    );
    let tone_stack = calibration.tone_stack;
    println!(
        "Tone stack at the factory defaults, power stage input: released {:.2} dB, \
         shipping {:.2} dB; scale {:.6e} -> {:.6e} ({:+.2} dB)",
        tone_stack.released_db,
        tone_stack.shipping_db,
        released.tone_stack,
        calibration.tables.tone_stack,
        db(f64::from(calibration.tables.tone_stack) / f64::from(released.tone_stack)),
    );
    sweep(
        "Power Drive, power amp seam",
        "power amp",
        &calibration.power,
        &released.power,
        &calibration.tables.power,
    );
    let anchor = calibration.anchor;
    println!(
        "Factory defaults, shipping minus released: power stage input {:+.3} dB, \
         power amp {:+.3} dB, output {:+.3} dB, output with the cabinet off {:+.3} dB",
        anchor.power_input_db, anchor.power_amp_db, anchor.output_db, anchor.output_cabinet_off_db,
    );
}

fn drift(committed: &[f32], fresh: &[f32]) -> f64 {
    committed
        .iter()
        .zip(fresh)
        .map(|(committed, fresh)| db(f64::from(*fresh) / f64::from(*committed)).abs())
        .fold(0., f64::max)
}

fn run() -> Result<(), String> {
    let clip_path = option("--clip")?;
    let data_path = option("--data")?;
    let bytes = fs::read(&clip_path).map_err(|error| format!("{clip_path}: {error}"))?;
    let calibration = calibration::measure(&calibration::clip(&bytes)?);
    report(&calibration);
    if env::args().any(|argument| argument == "--check") {
        let committed = LevelTables::CALIBRATED;
        let failures: Vec<String> = [
            (
                "PREAMP_SWEEP",
                &committed.preamp[..],
                &calibration.tables.preamp[..],
            ),
            (
                "TONE_STACK_SCALE",
                &[committed.tone_stack][..],
                &[calibration.tables.tone_stack][..],
            ),
            (
                "POWER_SWEEP",
                &committed.power[..],
                &calibration.tables.power[..],
            ),
        ]
        .into_iter()
        .map(|(name, committed, fresh)| (name, drift(committed, fresh)))
        .filter(|(_, drift)| *drift > TOLERANCE_DB)
        .map(|(name, drift)| format!("{name} drifted {drift:.3} dB (tolerance {TOLERANCE_DB} dB)"))
        .collect();
        if !failures.is_empty() {
            return Err(format!(
                "level tables are stale; run `just calibrate`:\n  {}",
                failures.join("\n  ")
            ));
        }
        println!("level tables are current");
        return Ok(());
    }
    fs::write(&data_path, source(calibration.tables))
        .map_err(|error| format!("{data_path}: {error}"))?;
    println!("wrote {data_path}");
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("calibrate: {error}");
        std::process::exit(1);
    }
}
